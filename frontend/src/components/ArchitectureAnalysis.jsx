import { useEffect, useState } from 'react';
import axios from 'axios';

let renderCounter = 0;
let mermaidPromise = null;

// Mermaid is large, so it is loaded only when a diagram is first shown.
function loadMermaid() {
    if (!mermaidPromise) {
        mermaidPromise = import('mermaid').then(module => {
            module.default.initialize({ startOnLoad: false, securityLevel: 'strict', theme: 'neutral' });
            return module.default;
        });
    }
    return mermaidPromise;
}

const TABS = [
    { id: 'summary', label: 'Summary' },
    { id: 'structure', label: 'Structure' },
    { id: 'modules', label: 'Modules' },
    { id: 'dependencies', label: 'Dependencies' },
    { id: 'class', label: 'Class Diagram' },
    { id: 'sequence', label: 'Sequence Diagram' },
];

function MermaidDiagram({ code }) {
    const [result, setResult] = useState({ svg: '', error: '' });

    useEffect(() => {
        let cancelled = false;

        async function draw() {
            try {
                const mermaid = await loadMermaid();
                await mermaid.parse(code);
                renderCounter += 1;
                const { svg } = await mermaid.render(`nexora-diagram-${renderCounter}`, code);
                if (!cancelled) setResult({ svg, error: '' });
            } catch {
                if (!cancelled) {
                    setResult({ svg: '', error: 'This diagram could not be rendered. The Mermaid code is shown below.' });
                }
            }
        }

        draw();
        return () => {
            cancelled = true;
        };
    }, [code]);

    return (
        <div>
            {result.error && <p className="mb-2 text-sm text-amber-800">{result.error}</p>}
            {result.svg && (
                <div
                    className="overflow-x-auto rounded-2xl border border-gray-200 bg-white p-4"
                    dangerouslySetInnerHTML={{ __html: result.svg }}
                />
            )}
            <details className="mt-3 text-sm text-gray-600" open={Boolean(result.error)}>
                <summary className="cursor-pointer">Mermaid code</summary>
                <pre className="mt-2 max-h-72 overflow-auto rounded-xl bg-gray-900 p-4 text-xs text-gray-100">{code}</pre>
            </details>
        </div>
    );
}

function Table({ columns, rows }) {
    return (
        <div className="overflow-x-auto rounded-2xl border border-gray-200">
            <table className="min-w-full text-left text-sm">
                <thead className="bg-gray-50 text-gray-700">
                    <tr>
                        {columns.map(column => (
                            <th key={column} className="px-4 py-3 font-semibold">{column}</th>
                        ))}
                    </tr>
                </thead>
                <tbody className="divide-y divide-gray-100 text-gray-700">
                    {rows.map((row, index) => (
                        <tr key={index}>
                            {row.map((cell, cellIndex) => (
                                <td key={cellIndex} className="px-4 py-2 align-top">{cell}</td>
                            ))}
                        </tr>
                    ))}
                </tbody>
            </table>
        </div>
    );
}

function SectionTitle({ children }) {
    return <h3 className="mb-3 mt-6 text-lg font-semibold text-gray-900 first:mt-0">{children}</h3>;
}

function SummaryTab({ data }) {
    return (
        <div>
            <SectionTitle>Architecture summary</SectionTitle>
            <p className="whitespace-pre-line text-sm leading-6 text-gray-700">{data.summary.text}</p>
            <p className="mt-2 text-xs text-gray-500">
                {data.summary.source === 'ollama'
                    ? 'Generated by Ollama (Qwen 2.5 Coder).'
                    : 'Generated from static analysis (Ollama was not available).'}
            </p>

            <SectionTitle>Technologies detected</SectionTitle>
            <div className="flex flex-wrap gap-2">
                {data.technologies.map(tech => (
                    <span key={tech} className="rounded-full bg-blue-50 px-3 py-1 text-xs font-medium text-blue-700">
                        {tech}
                    </span>
                ))}
            </div>

            <SectionTitle>Analysis details</SectionTitle>
            <p className="text-sm text-gray-700">
                {data.stats.analyzed_files} source files analysed out of {data.stats.total_files} files
                in {data.repository.owner}/{data.repository.name} (branch {data.repository.branch}).
            </p>
            {data.stats.warnings.length > 0 && (
                <ul className="mt-3 list-disc space-y-1 pl-5 text-sm text-amber-800">
                    {data.stats.warnings.slice(0, 10).map(warning => <li key={warning}>{warning}</li>)}
                </ul>
            )}
        </div>
    );
}

function StructureTab({ data }) {
    const { structure } = data;
    return (
        <div>
            <SectionTitle>Languages</SectionTitle>
            <div className="space-y-2">
                {structure.languages.map(item => (
                    <div key={item.language}>
                        <div className="flex justify-between text-sm text-gray-700">
                            <span>{item.language}</span>
                            <span>{item.files} files · {item.percent}%</span>
                        </div>
                        <div className="mt-1 h-2 rounded-full bg-gray-100">
                            <div className="h-2 rounded-full bg-blue-600" style={{ width: `${item.percent}%` }} />
                        </div>
                    </div>
                ))}
            </div>

            <SectionTitle>Top-level folders</SectionTitle>
            <Table
                columns={['Folder', 'Files']}
                rows={structure.top_level_folders.map(folder => [folder.name, folder.files])}
            />

            {structure.entry_points.length > 0 && (
                <>
                    <SectionTitle>Entry points</SectionTitle>
                    <ul className="list-disc space-y-1 pl-5 text-sm text-gray-700">
                        {structure.entry_points.map(entry => <li key={entry}>{entry}</li>)}
                    </ul>
                </>
            )}

            <SectionTitle>Directory tree</SectionTitle>
            <pre className="max-h-96 overflow-auto rounded-xl bg-gray-900 p-4 text-xs leading-5 text-gray-100">
                {structure.tree_text}
            </pre>
        </div>
    );
}

function ModulesTab({ data }) {
    return (
        <div>
            <SectionTitle>Components (folders)</SectionTitle>
            <Table
                columns={['Component', 'Role', 'Files', 'Classes', 'Functions', 'Depends on']}
                rows={data.components.map(c => [
                    c.name, c.role, c.files, c.classes, c.functions,
                    c.depends_on.length ? c.depends_on.join(', ') : '—',
                ])}
            />
            <SectionTitle>Modules (files)</SectionTitle>
            <Table
                columns={['File', 'Lines', 'Classes', 'Functions', 'Imports', 'Imported by']}
                rows={data.modules.map(m => [
                    m.path, m.lines,
                    m.classes.length ? m.classes.join(', ') : '—',
                    m.function_count, m.imports_internal, m.imported_by,
                ])}
            />
        </div>
    );
}

function DependenciesTab({ data }) {
    const { dependencies, diagrams } = data;
    return (
        <div>
            <SectionTitle>Dependency graph</SectionTitle>
            <MermaidDiagram code={diagrams.dependency} />

            <SectionTitle>Most depended-on files</SectionTitle>
            {dependencies.most_imported.length > 0 ? (
                <Table
                    columns={['File', 'Imported by']}
                    rows={dependencies.most_imported.map(item => [item.file, item.imported_by])}
                />
            ) : (
                <p className="text-sm text-gray-600">No internal imports were detected.</p>
            )}

            <SectionTitle>Circular dependencies</SectionTitle>
            {dependencies.circular_groups.length > 0 ? (
                <ul className="list-disc space-y-1 pl-5 text-sm text-red-700">
                    {dependencies.circular_groups.map(group => (
                        <li key={group.join('|')}>{group.join(' ⇄ ')}</li>
                    ))}
                </ul>
            ) : (
                <p className="text-sm text-gray-600">None detected.</p>
            )}

            <SectionTitle>External packages</SectionTitle>
            {dependencies.external_packages.length > 0 ? (
                <div className="flex flex-wrap gap-2">
                    {dependencies.external_packages.map(pkg => (
                        <span key={pkg.name} className="rounded-full bg-gray-100 px-3 py-1 text-xs text-gray-700">
                            {pkg.name} · {pkg.count}
                        </span>
                    ))}
                </div>
            ) : (
                <p className="text-sm text-gray-600">None detected.</p>
            )}
        </div>
    );
}

export default function ArchitectureAnalysis({ repositoryUrl }) {
    const [data, setData] = useState(null);
    const [loading, setLoading] = useState(false);
    const [error, setError] = useState('');
    const [tab, setTab] = useState('summary');

    async function runAnalysis() {
        setLoading(true);
        setError('');
        setData(null);
        setTab('summary');

        try {
            const response = await axios.post('http://127.0.0.1:8000/github/architecture', {
                url: repositoryUrl,
            });
            setData(response.data);
        } catch (err) {
            const detail = err.response?.data?.detail;
            setError(typeof detail === 'string' ? detail : 'Architecture analysis failed. Please try again.');
        } finally {
            setLoading(false);
        }
    }

    return (
        <section className="mt-8 rounded-3xl border border-gray-200 bg-white p-6 shadow-sm sm:p-8">
            <h2 className="text-2xl font-bold text-gray-900">Repository Architecture Analysis</h2>
            <p className="mt-2 text-sm text-gray-600">
                Analyse the project structure, modules, dependencies and generate architecture
                summaries with UML class and sequence diagrams.
            </p>
            <button
                type="button"
                onClick={runAnalysis}
                disabled={loading}
                className="mt-5 rounded-xl bg-gray-900 px-5 py-3 text-sm font-semibold text-white hover:bg-blue-600 disabled:opacity-60"
            >
                {loading ? 'Analysing architecture…' : 'Analyze Architecture'}
            </button>

            <div aria-live="polite" aria-busy={loading}>
                {error && <p className="mt-4 text-sm text-red-700">{error}</p>}
                {data && (
                    <div className="mt-6">
                        <div className="mb-5 flex flex-wrap gap-2" role="tablist">
                            {TABS.map(item => (
                                <button
                                    key={item.id}
                                    type="button"
                                    role="tab"
                                    aria-selected={tab === item.id}
                                    onClick={() => setTab(item.id)}
                                    className={`rounded-full px-4 py-2 text-sm font-medium ${
                                        tab === item.id
                                            ? 'bg-blue-600 text-white'
                                            : 'bg-gray-100 text-gray-700 hover:bg-gray-200'
                                    }`}
                                >
                                    {item.label}
                                </button>
                            ))}
                        </div>

                        {tab === 'summary' && <SummaryTab data={data} />}
                        {tab === 'structure' && <StructureTab data={data} />}
                        {tab === 'modules' && <ModulesTab data={data} />}
                        {tab === 'dependencies' && <DependenciesTab data={data} />}
                        {tab === 'class' && (
                            <div>
                                <SectionTitle>UML class diagram</SectionTitle>
                                <MermaidDiagram code={data.diagrams.class} />
                            </div>
                        )}
                        {tab === 'sequence' && (
                            <div>
                                <SectionTitle>UML sequence diagram</SectionTitle>
                                <p className="mb-3 text-sm text-gray-600">
                                    {data.diagrams.sequence_source === 'routes'
                                        ? 'Built from the API routes and the functions they call.'
                                        : 'No API routes were found, so this shows the import flow from the main entry file.'}
                                </p>
                                <MermaidDiagram code={data.diagrams.sequence} />
                            </div>
                        )}
                    </div>
                )}
            </div>
        </section>
    );
}
